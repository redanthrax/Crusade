def catmull(points, steps=12):
    pts = [points[0]] + points + [points[-1]]
    out = []
    for i in range(1, len(pts) - 2):
        p0, p1, p2, p3 = pts[i - 1], pts[i], pts[i + 1], pts[i + 2]
        for s in range(steps):
            t = s / steps
            t2, t3 = t * t, t * t * t
            out.append(tuple(
                0.5 * (2 * p1[k] + (-p0[k] + p2[k]) * t +
                       (2 * p0[k] - 5 * p1[k] + 4 * p2[k] - p3[k]) * t2 +
                       (-p0[k] + 3 * p1[k] - 3 * p2[k] + p3[k]) * t3)
                for k in range(2)))
    out.append(points[-1])
    return out


def gen_map():
    with open(os.path.join(GFX, "src/geo/near_east_50m.json")) as f:
        geo = json.load(f)
    land = scan_fill(geo["land"], FW, ART_H)
    lake = scan_fill(geo["lakes"], FW, ART_H)
    L = [[land[y][x] and not lake[y][x] for x in range(FW)]
         for y in range(ART_H)]

    def is_land(x, y):
        return 0 <= x < FW and 0 <= y < ART_H and L[y][x]

    # Seljuk lands: inside the box and connected to Konya (drops the Aegean
    # islands and Cyprus, which stayed Byzantine).
    sel = [[False] * FW for _ in range(ART_H)]
    kx, ky = map(int, proj(32.49, 37.87))
    stack = [(kx, ky)]
    while stack:
        x, y = stack.pop()
        if not is_land(x, y) or sel[y][x]:
            continue
        if not seljuk_box(*unproj(x + 0.5, y + 0.5)):
            continue
        sel[y][x] = True
        stack += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]

    # distance from land (chebyshev, capped) for coast ink and ripple lines
    INF = 99
    dist = [[0 if L[y][x] else INF for x in range(FW)] for y in range(ART_H)]
    frontier = [(x, y) for y in range(ART_H) for x in range(FW) if L[y][x]]
    for d in range(1, 7):
        nxt = []
        for x, y in frontier:
            for dy in (-1, 0, 1):
                for dx in (-1, 0, 1):
                    nx, ny = x + dx, y + dy
                    if 0 <= nx < FW and 0 <= ny < ART_H and dist[ny][nx] == INF:
                        dist[ny][nx] = d
                        nxt.append((nx, ny))
        frontier = nxt

    c = Canvas(FW, FH)
    for y in range(ART_H):
        for x in range(FW):
            if L[y][x]:
                edge = any(not is_land(x + dx, y + dy) and
                           0 <= x + dx < FW and 0 <= y + dy < ART_H
                           for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))
                frontier = sel[y][x] and any(
                    is_land(x + dx, y + dy) and not sel[y + dy][x + dx]
                    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))
                if sel[y][x]:
                    c.set(x, y, 8 if edge or frontier else 7)
                else:
                    c.set(x, y, 4 if edge else 5)
            else:
                d = dist[y][x]
                if d == 1:
                    c.set(x, y, 3)
                elif d == 3 and (x + y) % 2 == 0:
                    c.set(x, y, 2)
                else:
                    c.set(x, y, 1)
                    # engraved waves on open sea, period 16x16
                    if d > 5:
                        u, v = x % 16, y % 16
                        if (v == 4 and 3 <= u <= 5) or (v == 12 and 11 <= u <= 13):
                            c.set(x, y, 2)
                        elif (v == 3 and u == 4) or (v == 11 and u == 12):
                            c.set(x, y, 2)

    # parchment grain on open land, period 16 so the tiles repeat
    for y in range(ART_H):
        for x in range(FW):
            if c.px[y][x] in (5, 7):
                u, v = x % 16, y % 16
                if (u, v) in ((2, 3), (11, 9), (6, 13)):
                    c.set(x, y, 4 if c.px[y][x] == 5 else 8)
                elif (u, v) in ((13, 2), (5, 7)):
                    c.set(x, y, 6 if c.px[y][x] == 5 else 9)

    # mountains: little chevrons, light on the west face, dark on the east
    for chain in MOUNTAINS:
        pts = catmull([proj(*p) for p in chain], 20)
        acc, last = 0.0, None
        for p in pts:
            if last is not None:
                acc += math.hypot(p[0] - last[0], p[1] - last[1])
            last = p
            if acc < 6.0 and last is not pts[0]:
                continue
            acc = 0.0
            mx, my = int(p[0]), int(p[1])
            if not all(is_land(mx + dx, my + dy)
                       for dx in (-3, 3) for dy in (-2, 2)):
                continue
            s = sel[my][mx]
            lt, dk = (9, 8) if s else (6, 4)
            for i in range(3):
                c.set(mx - i, my - 2 + i, lt)
                c.set(mx + i, my - 2 + i, dk)
            c.set(mx + 1, my, dk)

    def label_ink(x, y):
        return 13 if not is_land(x, y) else 12

    for name, (lon, lat) in CITIES.items():
        x, y = (int(v) for v in proj(lon, lat))
        if name == "JERUSALEM":
            for dx, dy in ((0, -2), (0, -1), (0, 0), (0, 1), (0, 2),
                           (-1, -1), (1, -1)):
                c.set(x + dx, y + dy, 14)
            c.set(x - 1, y + 2, 12)
            c.set(x + 1, y + 2, 12)
        else:
            c.rect(x - 1, y - 1, x + 1, y + 1, 12)
            c.set(x + 1, y - 1, 14)
        ox, oy = LABELS[name]
        text3(c, name, x + ox, y + oy, label_ink)

    # region title revealed by palette fade (index 15)
    tx, ty = (int(v) for v in proj(31.4, 39.6))
    text3(c, "SELJUK TURKS", tx, ty, 15)
    bx, by = (int(v) for v in proj(20.0, 44.6))
    text3(c, "BYZANTIUM", bx, by, 12)

    # double rule frame
    for i, ink in ((0, 3), (1, 12), (2, 14), (3, 3)):
        c.hline(i, FW - i, i, ink)
        c.hline(i, FW - i, ART_H - 1 - i, ink)
        c.vline(i, i, ART_H - i, ink)
        c.vline(FW - 1 - i, i, ART_H - i, ink)

    # frame 1: the route, a dashed red line with a dark under-shadow
    r = Canvas(FW, FH)
    r.blit(c, 0, 0)
    path = catmull([proj(*p) for p in ROUTE], 16)
    dense = []
    for (x0, y0), (x1, y1) in zip(path, path[1:]):
        n = max(1, int(math.hypot(x1 - x0, y1 - y0) * 3))
        for i in range(n):
            t = i / n
            dense.append((x0 + (x1 - x0) * t, y0 + (y1 - y0) * t))
    dense.append(path[-1])
    acc, last, order = 0.0, None, []
    for x, y in dense:
        if last:
            acc += math.hypot(x - last[0], y - last[1])
        last = (x, y)
        px, py = int(x), int(y)
        if (acc % 6.0) < 4.0:
            if r.get(px, py + 1) not in (10,):
                r.set(px, py + 1, 11)
            r.set(px, py, 10)
        order.append((px, py))

    base, routed = c, r
    cells, seen = [], set()
    for x, y in order:
        for yy in (y, y + 1):
            cell = (yy // 8) * 30 + x // 8
            if cell in seen:
                continue
            tx_, ty_ = (cell % 30) * 8, (cell // 30) * 8
            differs = any(base.px[ty_ + j][tx_ + i] != routed.px[ty_ + j][tx_ + i]
                          for j in range(8) for i in range(8))
            if differs:
                seen.add(cell)
                cells.append(cell)
    for ty_ in range(FH // 8):
        for tx_ in range(30):
            cell = ty_ * 30 + tx_
            if cell not in seen and any(
                    base.px[ty_ * 8 + j][tx_ * 8 + i] !=
                    routed.px[ty_ * 8 + j][tx_ * 8 + i]
                    for j in range(8) for i in range(8)):
                cells.append(cell)

    save("intro_map", [base, routed], MAP_PAL,
         "Opening cinematic map (frame 0 base, frame 1 with the route).")
    write_route(cells)


def write_route(cells):
    h = ("/* Generated by tools/gen_intro_art.py -- do not edit. */\n"
         "#ifndef INTRO_ROUTE_H\n#define INTRO_ROUTE_H\n\n"
         "#include <tonc_types.h>\n\n"
         f"#define INTRO_ROUTE_CELLS {len(cells)}\n\n"
         "/* Screen cells (row*30+col) that differ between intro_map frame 0\n"
         " * and frame 1, in marching order from Bouillon to Jerusalem. */\n"
         "extern const u16 intro_routeCells[INTRO_ROUTE_CELLS];\n\n"
         "#endif\n")
    body = ",".join(str(v) for v in cells)
    cs = ("/* Generated by tools/gen_intro_art.py -- do not edit. */\n"
          '#include "intro_route.h"\n\n'
          f"const u16 intro_routeCells[INTRO_ROUTE_CELLS] = {{{body}}};\n")
    with open(os.path.join(GEN, "intro_route.h"), "w") as f:
        f.write(h)
    with open(os.path.join(GEN, "intro_route.c"), "w") as f:
        f.write(cs)


# --- shape helpers for the painted scenes ----------------------------------------

def poly(c, pts, ink):
    """Fills a pixel-space polygon (even-odd, pixel centres)."""
    ys = [p[1] for p in pts]
    for y in range(int(min(ys)), int(max(ys)) + 1):
        yc = y + 0.5
        xs = []
        for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]):
            if (y0 <= yc < y1) or (y1 <= yc < y0):
                xs.append(x0 + (yc - y0) * (x1 - x0) / (y1 - y0))
        xs.sort()
        for i in range(0, len(xs) - 1, 2):
            for x in range(math.ceil(xs[i] - 0.5), math.floor(xs[i + 1] - 0.5) + 1):
                c.set(x, y, ink)


def thick(c, x0, y0, x1, y1, ink, w=2):
    for o in range(w):
        line(c, x0 + o, y0, x1 + o, y1, ink)


def layer():
    return Canvas(FW, FH, fill=255)


def comp(dst, src, outline=None):
    """Composites a 255-keyed layer, optionally with a 1px outline."""
    if outline is not None:
        src.outline(outline, skip=(255,))
    dst.blit(src, 0, 0, key=255)


