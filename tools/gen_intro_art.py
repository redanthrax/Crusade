FLOOR_Y = 96


def stone_wall(c):
    for y in range(ART_H):
        for x in range(FW):
            row = y // 8
            off = 8 if row % 2 else 0
            mortar = y % 8 == 7 or (x + off) % 16 == 15
            c.set(x, y, 1 if mortar else 2)
    # floor flagstones
    for y in range(FLOOR_Y, ART_H):
        for x in range(FW):
            k = y - FLOOR_Y
            seam = k in (0, 5, 11) or ((x + k * 2) % 24 == 0 and k > 0)
            c.set(x, y, 1 if seam else 2)


def window(c, cx, top, w, h):
    x0, x1 = cx - w // 2, cx + w // 2
    arch = w // 2

    def inside(x, y):
        if y >= top + arch:
            return x0 <= x < x1
        # pointed arch: intersection of two circles radius w centred on the
        # opposite springers
        dy = (top + arch) - y
        return ((x - x0) ** 2 + dy ** 2 <= w * w and
                (x - x1 + 1) ** 2 + dy ** 2 <= w * w and x0 <= x < x1)

    for y in range(top - 2, top + h + 3):
        for x in range(x0 - 3, x1 + 3):
            near = any(inside(x + dx, y + dy) for dx in (-3, 0, 3) for dy in (-3, 0, 3))
            if near and not inside(x, y):
                c.set(x, y, 3)
    for y in range(top, top + h):
        for x in range(x0, x1):
            if not inside(x, y):
                continue
            lx, ly = x - x0, y - top
            # cross in gold on blue, border of red, lead lines
            mid = w // 2
            if abs(lx - mid) <= 1 and 8 <= ly <= h - 8 or \
                    abs(ly - (arch + 6)) <= 1 and 6 <= lx <= w - 7:
                ink = 7
            elif lx < 3 or lx >= w - 3 or ly >= h - 3:
                ink = 6 if (ly // 4) % 2 == 0 else 5
            elif (lx + ly) % 9 < 1 or (lx - ly) % 9 < 1:
                ink = 4
            else:
                ink = 5 if ((lx // 5 + ly // 6) % 3) else 8
            if lx in (2, w - 3) or ly == h - 3 or ly == arch + 2 and lx > 2 and lx < w - 3:
                ink = 4
            c.set(x, y, ink)
    c.rect(x0 - 4, top + h, x1 + 4, top + h + 2, 3)


def shaft(c, top_l, top_r, bot_l, bot_r, y0, y1):
    for y in range(y0, y1):
        t = (y - y0) / (y1 - y0)
        xl = top_l + (bot_l - top_l) * t
        xr = top_r + (bot_r - top_r) * t
        for x in range(int(xl), int(xr)):
            if c.get(x, y) in (1, 2) and (x + y) % 2 == 0:
                c.set(x, y, 9 if c.get(x, y) == 2 else 3)


def candle(c, x, y, tall):
    c.rect(x - 1, y - tall, x + 1, y, 14)
    c.set(x, y - tall - 1, 13)
    c.set(x, y - tall - 2, 13)
    c.set(x - 1, y - tall - 1, 13)
    c.rect(x - 2, y, x + 2, y + 1, 7)
    c.vline(x, y + 1, y + 5, 7)
    c.rect(x - 2, y + 5, x + 3, y + 6, 7)


def halo(c, cx, cy, r):
    for y in range(cy - r, cy + r + 1):
        for x in range(cx - r, cx + r + 1):
            d = math.hypot(x - cx, y - cy)
            if d > r or c.get(x, y) not in (1, 2, 3, 9):
                continue
            if d < r * 0.5 or (d < r * 0.85 and (x + y) % 2 == 0):
                c.set(x, y, 15)


