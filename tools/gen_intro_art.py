def text3_width(s):
    return 4 * len(s) - 1


def text3(c, s, x, y, ink):
    """ink: index or callable(x, y) -> index (so labels can adapt to what
    they are drawn over)."""
    for i, ch in enumerate(s):
        g = FONT3[ch]
        for r in range(5):
            for col in range(3):
                if g[r * 3 + col] == "1":
                    px, py = x + i * 4 + col, y + r
                    c.set(px, py, ink(px, py) if callable(ink) else ink)


