LON0, LAT1 = -8.0, 52.5
SY = ART_H / 22.0
SX = SY * math.cos(math.radians(41.5))


def proj(lon, lat):
    return (lon - LON0) * SX, (LAT1 - lat) * SY


def unproj(x, y):
    return x / SX + LON0, LAT1 - y / SY


def scan_fill(rings, w, h):
    """Even-odd scanline fill of lon/lat rings at pixel centres."""
    mask = [[False] * w for _ in range(h)]
    edges = []
    for ring in rings:
        pts = [proj(lon, lat) for lon, lat in ring]
        for i in range(len(pts) - 1):
            (x0, y0), (x1, y1) = pts[i], pts[i + 1]
            if y0 != y1:
                edges.append((x0, y0, x1, y1))
    for y in range(h):
        yc = y + 0.5
        xs = []
        for x0, y0, x1, y1 in edges:
            if (y0 <= yc < y1) or (y1 <= yc < y0):
                xs.append(x0 + (yc - y0) * (x1 - x0) / (y1 - y0))
        xs.sort()
        for i in range(0, len(xs) - 1, 2):
            a = max(0, math.ceil(xs[i] - 0.5))
            b = min(w - 1, math.floor(xs[i + 1] - 0.5))
            for x in range(a, b + 1):
                mask[y][x] = not mask[y][x]
    return mask


