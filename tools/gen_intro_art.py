# --- helpers -----------------------------------------------------------------

def unique_tiles(canvas):
    seen = set()
    for ty in range(canvas.h // 8):
        for tx in range(canvas.w // 8):
            t = tuple(tuple(canvas.px[ty * 8 + y][tx * 8:tx * 8 + 8])
                      for y in range(8))
            h = tuple(r[::-1] for r in t)
            v = t[::-1]
            hv = h[::-1]
            seen.add(min(t, h, v, hv))
    return len(seen)


def strip(frames):
    out = Canvas(FW, FH * len(frames))
    for i, f in enumerate(frames):
        out.blit(f, 0, i * FH)
    return out


def save(name, frames, pal, note):
    img = strip(frames)
    n = unique_tiles(img)
    assert n <= 512, f"{name}: {n} unique tiles > 512"
    assert len(pal) == 16
    write_png(os.path.join(GFX, name + ".png"), img, pal)
    with open(os.path.join(GFX, name + ".grit"), "w") as f:
        f.write(f"# {note}\n# Generated by tools/gen_intro_art.py.\n"
                "-gt -gB4 -mRtf -mLf -p -pn16\n")
    print(f"{name}.png: {len(frames)} frame(s), {n} unique tiles")
    return img


def line(c, x0, y0, x1, y1, ink):
    dx, dy = abs(x1 - x0), -abs(y1 - y0)
    sx, sy = (1 if x0 < x1 else -1), (1 if y0 < y1 else -1)
    err = dx + dy
    while True:
        c.set(x0, y0, ink)
        if x0 == x1 and y0 == y1:
            return
        e2 = 2 * err
        if e2 >= dy:
            err += dy
            x0 += sx
        if e2 <= dx:
            err += dx
            y0 += sy


def gothic(text, pt):
    """Trimmed 1bpp raster of `text` in UnifrakturCook."""
    rows = raster(text, pt, 8 * len(text) * pt // 10 + 40, pt * 2, pt * 3 // 2)
    y0, y1 = row_bounds(rows)
    x0, x1 = col_bounds(rows)
    return [r[x0:x1 + 1] for r in rows[y0:y1 + 1]]


def draw_bits(c, bits, ox, oy, ink):
    """ink: index or callable(row, col) -> index."""
    for y, r in enumerate(bits):
        for x, v in enumerate(r):
            if v:
                c.set(ox + x, oy + y, ink(y, x) if callable(ink) else ink)


