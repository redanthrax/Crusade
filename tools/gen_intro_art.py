def gold_ink(h):
    def ink(y, x):
        t = y / max(1, h - 1)
        if t < 0.18:
            return 4
        if t < 0.55:
            return 3
        if t < 0.85:
            return 2
        return 1
    return ink


def jerusalem_cross(c, cx, cy):
    """Cross potent with four crosslets, 13x13, gold."""
    c.rect(cx - 1, cy - 6, cx + 2, cy + 7, 3)
    c.rect(cx - 6, cy - 1, cx + 7, cy + 2, 3)
    for ex, ey in ((cx, cy - 6), (cx, cy + 6)):
        c.rect(ex - 2, ey, ex + 3, ey + 1, 3)
    for ex, ey in ((cx - 6, cy), (cx + 6, cy)):
        c.rect(ex, ey - 2, ex + 1, ey + 3, 3)
    c.vline(cx, cy - 5, cy + 6, 4)
    c.hline(cx - 5, cx + 6, cy, 4)
    for qx, qy in ((-4, -4), (4, -4), (-4, 4), (4, 4)):
        c.vline(cx + qx, cy + qy - 1, cy + qy + 2, 2)
        c.hline(cx + qx - 1, cx + qx + 2, cy + qy, 2)


def rule(c, x0, x1, y):
    c.hline(x0, x1, y, 2)
    c.hline(x0 + 2, x1 - 2, y + 1, 5)
    for x in (x0, x1 - 1):
        c.set(x, y - 1, 1)
        c.set(x, y + 1, 1)


def ornament(c, y):
    cx = FW // 2
    rule(c, 40, cx - 12, y)
    rule(c, cx + 12, FW - 40, y)
    jerusalem_cross(c, cx, y)


def gen_cards():
    frames = []

    c = Canvas(FW, FH)
    small = gothic("Anno Domini", 16)
    big = gothic("MXCV", 36)
    sw, bw = len(small[0]), len(big[0])
    y = 18
    draw_bits(c, small, (FW - sw) // 2, y, gold_ink(len(small)))
    y += len(small) + 8
    draw_bits(c, big, (FW - bw) // 2, y, gold_ink(len(big)))
    y += len(big) + 14
    ornament(c, y)
    frames.append(c)

    c = Canvas(FW, FH)
    big = gothic("Hierusalem", 30)
    bw = len(big[0])
    ornament(c, 22)
    draw_bits(c, big, (FW - bw) // 2, 40, gold_ink(len(big)))
    ornament(c, 40 + len(big) + 14)
    frames.append(c)

    save("intro_cards", frames, CARD_PAL,
         "Opening cinematic title cards (240x160 frames, one palette).")


